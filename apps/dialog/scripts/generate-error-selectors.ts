#!/usr/bin/env tsx

import * as AbiError from 'ox/AbiError'
import * as EIP7702Proxy from '../../../src/core/internal/_generated/contracts/EIP7702Proxy.js'
import * as Escrow from '../../../src/core/internal/_generated/contracts/Escrow.js'
import * as IthacaAccount from '../../../src/core/internal/_generated/contracts/IthacaAccount.js'
import * as LayerZeroSettler from '../../../src/core/internal/_generated/contracts/LayerZeroSettler.js'
import * as MultiSigSigner from '../../../src/core/internal/_generated/contracts/MultiSigSigner.js'
import * as Orchestrator from '../../../src/core/internal/_generated/contracts/Orchestrator.js'
import * as SimpleFunder from '../../../src/core/internal/_generated/contracts/SimpleFunder.js'
import * as SimpleSettler from '../../../src/core/internal/_generated/contracts/SimpleSettler.js'
import * as Simulator from '../../../src/core/internal/_generated/contracts/Simulator.js'

const errors = [
  EIP7702Proxy.abi,
  Escrow.abi,
  IthacaAccount.abi,
  LayerZeroSettler.abi,
  MultiSigSigner.abi,
  Orchestrator.abi,
  SimpleFunder.abi,
  SimpleSettler.abi,
  Simulator.abi,
]
  .flat()
  .filter((item) => item.type === 'error')
  .reduce(
    (selectors, error) => {
      selectors[AbiError.getSelector(error)] = error.name
      return selectors
    },
    {} as Record<string, string>,
  )

console.log(`// this file has been generated by scripts/generate-error-selectors.ts

import type { Hex } from 'viem'

// biome-ignore assist/source/useSortedKeys: Selector keys are sorted lexicographically.
export const errorSelectors: Record<Hex, string> = {
${Object.entries(errors)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([selector, name]) => `  '${selector}': '${name}',`)
  .join('\n')}
} as const`)
